#!/usr/bin/env node
/**
 * Writes the two files that carry this repo's sources into ck-exec and into Crowdy Studio:
 *
 *  - `exec/construct/src/catalog.rs`: the world hub's program catalog, from PROGRAM_CATALOG in
 *    `model/catalog.mjs`. A ck-exec build takes Rust sources only (no data files, no
 *    `include_str!`), so the catalog is compiled in as constants.
 *  - `mods/templates/exec-mods.mjs`: the SERVER starter mods (`exec/mods/<id>`) as the strings
 *    `npm run setup` / `seed` publish as Studio Common Files, each Cargo.toml's `ckx-sdk` line
 *    pointed at the platform's copy instead of a local checkout.
 *
 *   node scripts/build-exec-sources.mjs          rewrite both
 *   node scripts/build-exec-sources.mjs --check  exit 1 when either is not what it would write
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { PROGRAM_CATALOG } from '../model/catalog.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const CATALOG_RS = 'exec/construct/src/catalog.rs';
export const EXEC_MODS_MJS = 'mods/templates/exec-mods.mjs';
const MODS_DIR = 'exec/mods';

/** Crowdy Studio's build replaces the line; the version only reads well (ck-exec's SDK today). */
const CKX_SDK_VERSION = '0.6.0';

function rustString(value) {
  let out = '"';
  for (const ch of String(value)) {
    const code = ch.codePointAt(0) ?? 0;
    if (ch === '"') out += '\\"';
    else if (ch === '\\') out += '\\\\';
    else if (ch === '\n') out += '\\n';
    else if (ch === '\r') out += '\\r';
    else if (ch === '\t') out += '\\t';
    else if (code < 0x20 || code === 0x7f) out += `\\u{${code.toString(16)}}`;
    else out += ch;
  }
  return `${out}"`;
}

export function renderCatalog(catalog = PROGRAM_CATALOG) {
  const ids = new Set();
  const scenes = new Set();
  for (const p of catalog) {
    if (!Number.isInteger(p.programId) || p.programId < 1 || p.programId > 255)
      throw new Error(`programId ${p.programId} must be 1-255 (0 is the holodeck)`);
    if (typeof p.sceneId !== 'string' || !p.sceneId) throw new Error('every program names a scene');
    if (ids.has(p.programId) || scenes.has(p.sceneId))
      throw new Error(`program ${p.programId} / ${p.sceneId} appears twice`);
    ids.add(p.programId);
    scenes.add(p.sceneId);
  }
  return [
    '//! The programs the holodeck offers. Generated by scripts/build-exec-sources.mjs from',
    '//! PROGRAM_CATALOG in model/catalog.mjs; do not edit.',
    '',
    'use crate::world::Program;',
    '',
    '#[rustfmt::skip]',
    'pub const PROGRAMS: &[Program] = &[',
    ...catalog.map(
      (p) =>
        `    Program { program_id: ${p.programId}, scene_id: ${rustString(p.sceneId)}, name: ${rustString(p.name)}, description: ${rustString(p.description)} },`,
    ),
    '];',
    '',
  ].join('\n');
}

/** A starter's Cargo.toml as a player's project carries it: `ckx-sdk` is the platform's. */
export function publishedCargo(cargo) {
  const rewritten = cargo.replace(
    /(?:^#.*\n)*^ckx-sdk\s*=.*$/m,
    `# Crowdy Studio's build replaces this line with the platform's copy of ckx-sdk.\nckx-sdk = "${CKX_SDK_VERSION}"`,
  );
  if (rewritten === cargo) throw new Error('a starter mod depends on ckx-sdk');
  return rewritten;
}

/** Each starter mod's crate: exactly a Cargo.toml and a src/lib.rs, which Common Files carry. */
export function modSources() {
  const out = {};
  for (const id of readdirSync(path.join(root, MODS_DIR)).sort()) {
    const dir = path.join(root, MODS_DIR, id);
    const rust = readdirSync(path.join(dir, 'src'));
    if (rust.join() !== 'lib.rs')
      throw new Error(`${MODS_DIR}/${id}: a starter mod is one src/lib.rs`);
    out[id] = {
      'Cargo.toml': publishedCargo(readFileSync(path.join(dir, 'Cargo.toml'), 'utf8')),
      'src/lib.rs': readFileSync(path.join(dir, 'src', 'lib.rs'), 'utf8'),
    };
  }
  return out;
}

export function renderModSources(sources = modSources()) {
  const lines = [
    '// Generated by scripts/build-exec-sources.mjs from exec/mods/*; do not edit.',
    '// The SERVER starter mods as Crowdy Studio Common Files carry them (see index.mjs).',
    '',
    '/** @type {Readonly<Record<string, Readonly<Record<string, string>>>>} */',
    'export const EXEC_MOD_SOURCES = {',
  ];
  for (const [id, files] of Object.entries(sources)) {
    lines.push(`  ${JSON.stringify(id)}: {`);
    for (const [file, content] of Object.entries(files))
      lines.push(`    ${JSON.stringify(file)}: ${JSON.stringify(content)},`);
    lines.push('  },');
  }
  lines.push('};', '');
  return lines.join('\n');
}

/** Every generated file and what it should contain. */
export function generatedFiles() {
  return { [CATALOG_RS]: renderCatalog(), [EXEC_MODS_MJS]: renderModSources() };
}

/** Generated files that differ from what they should contain. */
export function staleFiles() {
  return Object.entries(generatedFiles())
    .filter(([file, content]) => {
      try {
        return readFileSync(path.join(root, file), 'utf8') !== content;
      } catch {
        return true;
      }
    })
    .map(([file]) => file);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const stale = staleFiles();
    if (stale.length) {
      console.error(
        `${stale.join(', ')} ${stale.length > 1 ? 'are' : 'is'} stale: run npm run build:exec-sources`,
      );
      process.exit(1);
    }
    console.log('exec sources are current');
  } else {
    for (const [file, content] of Object.entries(generatedFiles())) {
      writeFileSync(path.join(root, file), content);
      console.log(`wrote ${file}`);
    }
  }
}
